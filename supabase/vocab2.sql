  return coalesce((select jsonb_agg(public._vocab2_card(v) order by i.position, v.id)
                     from public.vocabulary_set_items i join public.vocabulary v on v.id = i.word_id
                    where i.set_id = p_id), '[]'::jsonb);
end;
