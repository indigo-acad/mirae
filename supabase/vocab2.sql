-- ---------- 7. Преподаватель: база слов школы ----------
-- поиск: p_filter = all | unchecked (не проверено) | used (есть у учеников)
create or replace function public.teacher_words(p_name text, p_pin text, p_lang text, p_query text, p_filter text, p_limit int)
returns jsonb as $fn$
declare q text := lower(trim(coalesce(p_query, ''))); lim int := least(greatest(coalesce(p_limit, 50), 1), 200);
begin
  perform public._school_teacher(p_name, p_pin);
  return coalesce((select jsonb_agg(x.j order by x.norm, x.id) from (
      select v.id, v.norm, public._vocab2_card(v) || jsonb_build_object(
               'students', (select count(*) from public.student_vocabulary sv where sv.word_id = v.id),
               'sets', (select count(*) from public.vocabulary_set_items i where i.word_id = v.id)) as j
        from public.vocabulary v
       where (coalesce(p_lang, '') = '' or v.lang = p_lang)
         and (q = '' or v.norm like '%' || q || '%' or lower(v.tr_ru::text) like '%' || q || '%' or lower(v.tr_ko::text) like '%' || q || '%')
         and (coalesce(p_filter, 'all') <> 'unchecked' or not v.checked)
         and (coalesce(p_filter, 'all') <> 'used' or exists (select 1 from public.student_vocabulary sv where sv.word_id = v.id))
       order by v.norm, v.id limit lim) x), '[]'::jsonb);
end;
$fn$ language plpgsql stable security definer set search_path = public, extensions;

-- сохранить слово: без id — новое, с id — изменить. Сохранённое преподавателем считается проверенным
create or replace function public.teacher_word_save(p_name text, p_pin text, p_word jsonb)
returns jsonb as $fn$
declare
  t text;
  w jsonb := coalesce(p_word, '{}'::jsonb);
  wid bigint;
  l text := coalesce(w->>'lang', '');
  wd text := trim(regexp_replace(normalize(coalesce(w->>'word', ''), NFC), '\s+', ' ', 'g'));
  nrm text := lower(trim(regexp_replace(normalize(coalesce(w->>'word', ''), NFC), '\s+', ' ', 'g')));
  ps text := coalesce(w->>'pos', '');
  sn text := trim(regexp_replace(coalesce(w->>'sense', ''), '\s+', ' ', 'g'));
  lv text := trim(coalesce(w->>'level', ''));
  i1 text := trim(coalesce(w->>'ipa_uk', ''));
  i2 text := trim(coalesce(w->>'ipa_us', ''));
  ex text := trim(coalesce(w->>'explanation', ''));
  img text := trim(coalesce(w->>'image', ''));
  old public.vocabulary;
  r public.vocabulary;
begin
  t := public._school_teacher(p_name, p_pin);
  if jsonb_typeof(w) <> 'object' or length(w::text) > 16000 then raise exception 'bad_input'; end if;
  if coalesce(w->>'id', '') !~ '^\d{0,18}$' then raise exception 'bad_input'; end if;
  wid := nullif(w->>'id', '')::bigint;
  if l not in ('ko', 'en') or wd = '' or length(wd) > 120 or length(sn) > 80 or length(lv) > 20 or length(i1) > 120 or length(i2) > 120
     or length(ex) > 1000 or (img <> '' and (img !~ '^https://' or length(img) > 500)) then raise exception 'bad_input'; end if;
  -- источники полей: {"поле": "источник"}, короткие строки; без ключа sources отметки не меняются
  if w ? 'sources' and (jsonb_typeof(w->'sources') <> 'object' or length((w->'sources')::text) > 2000
     or exists (select 1 from jsonb_each(w->'sources') e where jsonb_typeof(e.value) <> 'string' or length(e.key) > 40 or length(e.value #>> '{}') > 40)) then
    raise exception 'bad_input';
  end if;
  if wid is not null then
    select * into old from public.vocabulary where id = wid;
    if not found then raise exception 'no_word'; end if;
    -- слово уже у учеников: их карточки записаны под прежним написанием, менять его нельзя
    if (old.norm <> nrm or old.lang <> l)
       and exists (select 1 from public.student_vocabulary where word_id = wid) then raise exception 'in_use'; end if;
    if old.lang <> l and exists (select 1 from public.vocabulary_set_items where word_id = wid) then raise exception 'in_use'; end if;
    update public.vocabulary set lang = l, word = wd, norm = nrm, pos = ps, sense = sn, level = lv,
           sources = case when w ? 'sources' then w->'sources' else sources end,
           tr_ru = public._vocab2_strs(w->'tr_ru', 10, 160), tr_ko = public._vocab2_strs(w->'tr_ko', 10, 160),
           ipa_uk = i1, ipa_us = i2, examples = public._vocab2_examples(w->'examples'), explanation = ex,
           synonyms = public._vocab2_strs(w->'synonyms', 12, 80), image = img,
           topics = public._vocab2_strs(w->'topics', 10, 40), checked = true, updated_at = now()
     where id = wid returning * into r;
  else
    insert into public.vocabulary(lang, word, norm, pos, sense, level, tr_ru, tr_ko, ipa_uk, ipa_us, examples, explanation,
                                  synonyms, image, topics, checked, sources, created_by)
    values (l, wd, nrm, ps, sn, lv, public._vocab2_strs(w->'tr_ru', 10, 160), public._vocab2_strs(w->'tr_ko', 10, 160),
            i1, i2, public._vocab2_examples(w->'examples'), ex, public._vocab2_strs(w->'synonyms', 12, 80), img,
            public._vocab2_strs(w->'topics', 10, 40), true, coalesce(w->'sources', '{}'::jsonb), t)
    returning * into r;
  end if;
  return public._vocab2_card(r);
exception
  when unique_violation then raise exception 'exists';
  when check_violation then raise exception 'bad_input';
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- удалить слово из базы можно, только если его нет у учеников
create or replace function public.teacher_word_delete(p_name text, p_pin text, p_id bigint)
returns void as $fn$
begin
  perform public._school_teacher(p_name, p_pin);
  if exists (select 1 from public.student_vocabulary where word_id = p_id) then raise exception 'in_use'; end if;
  delete from public.vocabulary where id = p_id;
  if not found then raise exception 'no_word'; end if;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- ---------- 8. Преподаватель: словари ----------
-- все словари школы; менять словарь может его автор и владелец школы, назначать — любой преподаватель
create or replace function public.teacher_sets(p_name text, p_pin text)
returns jsonb as $fn$
declare t text; own boolean;
begin
  t := public._school_teacher(p_name, p_pin);
  own := exists (select 1 from public.teachers where name = t and role = 'owner');
  return coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'lang', s.lang, 'title', s.title, 'topic', s.topic, 'level', s.level,
              'description', s.description, 'author', s.author, 'mine', own or s.author = t, 'material', s.lang || '-words-' || s.id,
              'words', (select count(*) from public.vocabulary_set_items i where i.set_id = s.id),
              'students', (select count(*) from public.assignments a where a.material_id = s.lang || '-words-' || s.id),
              'updated_at', s.updated_at) order by s.updated_at desc)
           from public.vocabulary_sets s), '[]'::jsonb);
end;
$fn$ language plpgsql stable security definer set search_path = public, extensions;

create or replace function public._vocab2_set_editable(p_teacher text, p_set bigint)
returns void as $fn$
begin
  if not exists (select 1 from public.vocabulary_sets where id = p_set) then raise exception 'no_set'; end if;
  if not exists (select 1 from public.vocabulary_sets s where s.id = p_set
                    and (s.author = p_teacher or exists (select 1 from public.teachers where name = p_teacher and role = 'owner'))) then
    raise exception 'not_author';
  end if;
end;
$fn$ language plpgsql stable security definer set search_path = public, extensions;
revoke execute on function public._vocab2_set_editable(text, bigint) from public, anon, authenticated;

-- создать (без id) или изменить словарь; у каждого словаря есть строка в materials, чтобы назначать его со сроком
create or replace function public.teacher_set_save(p_name text, p_pin text, p_set jsonb)
returns jsonb as $fn$
declare
  t text; s jsonb := coalesce(p_set, '{}'::jsonb); sid bigint;
  l text := coalesce(s->>'lang', '');
  ti text := trim(coalesce(s->>'title', ''));
  tp text := trim(coalesce(s->>'topic', ''));
  lv text := trim(coalesce(s->>'level', ''));
  ds text := trim(coalesce(s->>'description', ''));
  old_lang text;
begin
  t := public._school_teacher(p_name, p_pin);
  if jsonb_typeof(s) <> 'object' or coalesce(s->>'id', '') !~ '^\d{0,18}$' then raise exception 'bad_input'; end if;
  if l not in ('ko', 'en') or ti = '' or length(ti) > 120 or length(tp) > 80 or length(lv) > 20 or length(ds) > 500 then
    raise exception 'bad_input';
  end if;
  sid := nullif(s->>'id', '')::bigint;
  if sid is null then
    insert into public.vocabulary_sets(lang, title, topic, level, description, author) values (l, ti, tp, lv, ds, t) returning id into sid;
  else
    perform public._vocab2_set_editable(t, sid);
    select lang into old_lang from public.vocabulary_sets where id = sid;
    if old_lang <> l and exists (select 1 from public.vocabulary_set_items where set_id = sid) then raise exception 'in_use'; end if;
    if old_lang <> l then delete from public.materials where id = old_lang || '-words-' || sid; end if;
    update public.vocabulary_sets set lang = l, title = ti, topic = tp, level = lv, description = ds, updated_at = now() where id = sid;
  end if;
  insert into public.materials(id, section, kind, title, level, path, sort)
  values (l || '-words-' || sid, case l when 'en' then 'english' else 'korean' end, 'words', 'Словарь · ' || ti, lv,
          'words.html?lang=' || l || '&set=' || sid, 100000 + sid::int)
  on conflict (id) do update set title = excluded.title, level = excluded.level, path = excluded.path;
  return jsonb_build_object('id', sid, 'material', l || '-words-' || sid);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- удалить словарь: снимается и его назначение; слова у учеников остаются
create or replace function public.teacher_set_delete(p_name text, p_pin text, p_id bigint)
returns void as $fn$
declare t text; m text;
begin
  t := public._school_teacher(p_name, p_pin);
  perform public._vocab2_set_editable(t, p_id);
  m := public._vocab2_material(p_id);
  delete from public.vocabulary_sets where id = p_id;
  delete from public.materials where id = m;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- слова словаря по порядку
create or replace function public.teacher_set_words(p_name text, p_pin text, p_id bigint)
returns jsonb as $fn$
begin
  perform public._school_teacher(p_name, p_pin);
