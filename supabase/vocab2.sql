-- ---------- 4. Служебные функции (сайт их не вызывает) ----------
-- массив строк из jsonb: обрезает пробелы, убирает пустые и повторы, не больше n штук по m символов
create or replace function public._vocab2_strs(p jsonb, n int, m int)
returns jsonb as $fn$
declare r jsonb := '[]'::jsonb; x jsonb; s text;
begin
  if p is null or jsonb_typeof(p) = 'null' then return r; end if;
  if jsonb_typeof(p) <> 'array' or jsonb_array_length(p) > n then raise exception 'bad_input'; end if;
  for x in select * from jsonb_array_elements(p) loop
    if jsonb_typeof(x) <> 'string' then raise exception 'bad_input'; end if;
    s := trim(regexp_replace(x #>> '{}', '\s+', ' ', 'g'));
    if length(s) > m then raise exception 'bad_input'; end if;
    if s <> '' and not r @> jsonb_build_array(s) then r := r || jsonb_build_array(s); end if;
  end loop;
  return r;
end;
$fn$ language plpgsql immutable set search_path = public, extensions;

-- примеры: [{"s": "...", "t": "..."}], не больше 10, по 300 символов
create or replace function public._vocab2_examples(p jsonb)
returns jsonb as $fn$
declare r jsonb := '[]'::jsonb; x jsonb; s text; t text;
begin
  if p is null or jsonb_typeof(p) = 'null' then return r; end if;
  if jsonb_typeof(p) <> 'array' or jsonb_array_length(p) > 10 then raise exception 'bad_input'; end if;
  for x in select * from jsonb_array_elements(p) loop
    if jsonb_typeof(x) <> 'object' then raise exception 'bad_input'; end if;
    s := trim(coalesce(x->>'s', '')); t := trim(coalesce(x->>'t', ''));
    if length(s) > 300 or length(t) > 300 then raise exception 'bad_input'; end if;
    if s <> '' then r := r || jsonb_build_array(jsonb_build_object('s', s, 't', t)); end if;
  end loop;
  return r;
end;
$fn$ language plpgsql immutable set search_path = public, extensions;

