-- связать карточку ученика из vocab с базой школы; слова нет в базе — добавить его туда.
-- Перевод и пример из карточки попадают в базу, только если слово дал преподаватель или урок.
create or replace function public._vocab2_link(p_student text, p_card text, p_data jsonb)
returns void as $fn$
declare
  l text := split_part(coalesce(p_card, ''), ':', 1);
  nrm text := substr(coalesce(p_card, ''), length(split_part(coalesce(p_card, ''), ':', 1)) + 2);
  src text := left(coalesce(nullif(p_data->>'src', ''), 'self'), 60);
  official boolean;
  tr text := left(trim(coalesce(p_data->>'t', '')), 160);
  ex text := left(trim(coalesce(p_data->>'ex', '')), 300);
  et text := left(trim(coalesce(p_data->>'et', '')), 300);
  wid bigint;
begin
  if l not in ('ko', 'en') or nrm = '' or length(nrm) > 120 then return; end if;
  if not exists (select 1 from public.progress where site = 'school' and name = p_student) then return; end if;
  official := src = 'teacher' or src like 'lesson:%' or src like 'set:%';
  select word_id into wid from public.student_vocabulary where site = 'school' and student = p_student and card_id = p_card;
  if wid is null then
    select id into wid from public.vocabulary where lang = l and norm = nrm order by (pos = '' and sense = '') desc, id limit 1;
  end if;
  if wid is null then
    insert into public.vocabulary(lang, word, norm, tr_ru, examples, created_by)
    values (l, left(coalesce(nullif(trim(p_data->>'w'), ''), nrm), 120), nrm,
            case when official and tr <> '' then jsonb_build_array(tr) else '[]'::jsonb end,
            case when official and ex <> '' then jsonb_build_array(jsonb_build_object('s', ex, 't', et)) else '[]'::jsonb end,
            'auto')
    on conflict (lang, norm, pos, sense) do nothing
    returning id into wid;
    if wid is null then
      select id into wid from public.vocabulary where lang = l and norm = nrm order by (pos = '' and sense = '') desc, id limit 1;
    end if;
  elsif official then
    -- пустые поля непроверенного слова дополняем тем, что дал преподаватель
    update public.vocabulary
       set tr_ru = case when tr_ru = '[]'::jsonb and tr <> '' then jsonb_build_array(tr) else tr_ru end,
           examples = case when examples = '[]'::jsonb and ex <> '' then jsonb_build_array(jsonb_build_object('s', ex, 't', et)) else examples end,
           updated_at = now()
     where id = wid and not checked and ((tr_ru = '[]'::jsonb and tr <> '') or (examples = '[]'::jsonb and ex <> ''));
  end if;
  insert into public.student_vocabulary(site, student, card_id, word_id, source, difficult, note)
  values ('school', p_student, p_card, wid, src, coalesce(p_data->>'star', '') in ('1', 'true'), left(coalesce(p_data->>'note', ''), 500))
  on conflict (site, student, card_id) do update
    set difficult = excluded.difficult, note = excluded.note, updated_at = now(),
        source = case when public.student_vocabulary.source like 'set:%' then public.student_vocabulary.source else excluded.source end;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- копия изменений из vocab. Ошибка здесь не мешает словарю ученика: слово сохранится, копия догонит при следующем изменении
create or replace function public._vocab2_mirror()
returns trigger as $fn$
begin
  begin
    if tg_op = 'DELETE' then
      delete from public.student_vocabulary where site = 'school' and student = old.student and card_id = old.id;
    elsif new.id <> '_settings' then
      perform public._vocab2_link(new.student, new.id, new.data);
    end if;
  exception when others then
    raise warning 'vocab2: копия слова пропущена (%)', sqlerrm;
  end;
  return null;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;
drop trigger if exists vocab2_mirror on public.vocab;
create trigger vocab2_mirror after insert or update or delete on public.vocab
  for each row execute function public._vocab2_mirror();

revoke execute on function public._vocab2_strs(jsonb, int, int) from public, anon, authenticated;
