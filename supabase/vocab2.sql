-- ---------- 1. База слов школы ----------
-- Одна строка на значение слова: язык + слово + часть речи + значение. light «лёгкий» и light «светлый» — две строки,
-- у каждой свои переводы, примеры и упражнения. Карточку заполняет и подтверждает преподаватель;
-- слова, которые уже есть у учеников, появляются здесь сами (checked = false — ещё не проверено преподавателем).
-- sources — откуда взяты поля карточки ({"ipa_uk": "cambridge", "tr_ko": "naver"}): словари подключаются как сменные
-- источники, и по этой отметке их данные можно найти, обновить или убрать, если изменятся условия лицензии.
create table if not exists public.vocabulary (
  id bigint generated by default as identity primary key,
  lang text not null check (lang in ('ko', 'en')),
  word text not null check (length(word) between 1 and 120),
  norm text not null check (length(norm) between 1 and 120),          -- слово строчными, как в id карточки ученика
  pos text not null default '' check (pos in ('', 'noun', 'verb', 'adjective', 'adverb', 'pronoun', 'preposition',
                                              'conjunction', 'interjection', 'phrase', 'phrasal_verb', 'idiom',
                                              'number', 'particle', 'determiner')),
  sense text not null default '' check (length(sense) <= 80),                       -- какое значение, если их несколько
  level text not null default '' check (length(level) <= 20),
  tr_ru jsonb not null default '[]' check (jsonb_typeof(tr_ru) = 'array'),        -- переводы на русский
  tr_ko jsonb not null default '[]' check (jsonb_typeof(tr_ko) = 'array'),        -- переводы на корейский (для английских слов)
  ipa_uk text not null default '' check (length(ipa_uk) <= 120),
  ipa_us text not null default '' check (length(ipa_us) <= 120),
  examples jsonb not null default '[]' check (jsonb_typeof(examples) = 'array'),  -- [{"s": пример, "t": перевод}]
  explanation text not null default '' check (length(explanation) <= 1000),
  synonyms jsonb not null default '[]' check (jsonb_typeof(synonyms) = 'array'),
  image text not null default '' check (image = '' or (image ~ '^https://' and length(image) <= 500)),
  topics jsonb not null default '[]' check (jsonb_typeof(topics) = 'array'),
  checked boolean not null default false,
  sources jsonb not null default '{}' check (jsonb_typeof(sources) = 'object'),
  created_by text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (lang, norm, pos, sense)
);
create index if not exists vocabulary_lang_norm on public.vocabulary(lang, norm);

-- ---------- 2. Словари преподавателя ----------
create table if not exists public.vocabulary_sets (
  id bigint generated by default as identity primary key,
  lang text not null check (lang in ('ko', 'en')),
  title text not null check (length(title) between 1 and 120),
  topic text not null default '' check (length(topic) <= 80),
  level text not null default '' check (length(level) <= 20),
  description text not null default '' check (length(description) <= 500),
  author text references public.teachers(name) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.vocabulary_set_items (
  set_id bigint not null references public.vocabulary_sets(id) on delete cascade,
  word_id bigint not null references public.vocabulary(id) on delete cascade,
  position int not null default 0,
  primary key (set_id, word_id)
);
create index if not exists vocabulary_set_items_word on public.vocabulary_set_items(word_id);

-- ---------- 3. Слова ученика ----------
-- Копия каждого слова из vocab с привязкой к базе школы: откуда пришло, отметка «сложное», личная заметка.
-- Удаление ученика удаляет и его строки.
create table if not exists public.student_vocabulary (
  site text not null default 'school' check (site = 'school'),
  student text not null,
  card_id text not null,                                   -- id карточки в vocab: «язык:слово»
  word_id bigint not null references public.vocabulary(id) on delete restrict,
  source text not null default 'self',                     -- self | teacher | lesson:<id> | set:<id>
  difficult boolean not null default false,
  note text not null default '' check (length(note) <= 500),
  added_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (site, student, card_id),
  foreign key (site, student) references public.progress(site, name) on delete cascade
);
create index if not exists student_vocabulary_word on public.student_vocabulary(word_id);

