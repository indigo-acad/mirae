-- состав словаря целиком: список id слов в нужном порядке
create or replace function public.teacher_set_words_save(p_name text, p_pin text, p_id bigint, p_words jsonb)
returns void as $fn$
declare t text; ws jsonb := coalesce(p_words, '[]'::jsonb); l text;
begin
  t := public._school_teacher(p_name, p_pin);
  perform public._vocab2_set_editable(t, p_id);
  if jsonb_typeof(ws) <> 'array' or jsonb_array_length(ws) > 500 then raise exception 'bad_input'; end if;
  if exists (select 1 from jsonb_array_elements(ws) x where jsonb_typeof(x) <> 'number' or x::text !~ '^\d{1,18}$') then
    raise exception 'bad_input';
  end if;
  select lang into l from public.vocabulary_sets where id = p_id;
  if exists (select 1 from jsonb_array_elements_text(ws) x
              where not exists (select 1 from public.vocabulary v where v.id = x::bigint and v.lang = l)) then
    raise exception 'no_word';
  end if;
  delete from public.vocabulary_set_items where set_id = p_id;
  insert into public.vocabulary_set_items(set_id, word_id, position)
  select p_id, x.v::bigint, min(x.o)::int from jsonb_array_elements_text(ws) with ordinality x(v, o) group by x.v;
  update public.vocabulary_sets set updated_at = now() where id = p_id;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- назначить словарь ученику: задание со сроком и слова в его словарь (новые — в очередь новых слов, знакомые не трогаем).
-- p_words — id отмеченных слов словаря, если ученику нужна только часть; null — весь словарь.
create or replace function public.teacher_set_assign_words(p_name text, p_pin text, p_student text, p_id bigint, p_due date, p_note text, p_words jsonb)
returns jsonb as $fn$
declare
  t text; s text := lower(trim(coalesce(p_student, ''))); m text;
  ms numeric := floor(extract(epoch from clock_timestamp()) * 1000);
  pick jsonb := case when p_words is null or jsonb_typeof(p_words) = 'null' then null else p_words end;
  v public.vocabulary; card text; i int := 0; added int := 0; linked int := 0;
begin
  t := public._school_teacher(p_name, p_pin);
  perform public._school_mine(t, s);
  if not exists (select 1 from public.progress where site = 'school' and name = s)
     or exists (select 1 from public.teachers where name = s) then raise exception 'no_student'; end if;
  m := public._vocab2_material(p_id);
  if m is null then raise exception 'no_set'; end if;
  if length(coalesce(p_note, '')) > 300 then raise exception 'bad_input'; end if;
  if pick is not null then
    if jsonb_typeof(pick) <> 'array' or jsonb_array_length(pick) = 0 or jsonb_array_length(pick) > 500 then raise exception 'bad_input'; end if;
    if exists (select 1 from jsonb_array_elements(pick) x where jsonb_typeof(x) <> 'number' or x::text !~ '^\d{1,18}$') then
      raise exception 'bad_input';
    end if;
    if exists (select 1 from jsonb_array_elements_text(pick) x
                where not exists (select 1 from public.vocabulary_set_items it where it.set_id = p_id and it.word_id = x::bigint)) then
      raise exception 'no_word';
    end if;
  end if;
  insert into public.assignments(student, material_id, due, note) values (s, m, p_due, coalesce(p_note, ''))
    on conflict (student, material_id) do update set due = excluded.due, note = excluded.note;
  for v in select w.* from public.vocabulary_set_items it join public.vocabulary w on w.id = it.word_id
            where it.set_id = p_id and (pick is null or pick @> to_jsonb(w.id)) order by it.position, w.id loop
    card := v.lang || ':' || v.norm;
    i := i + 1;
    if not exists (select 1 from public.vocab where student = s and id = card) then
      insert into public.vocab(student, id, data, updated_at)
      values (s, card, jsonb_strip_nulls(jsonb_build_object('id', card, 'l', v.lang, 'w', v.word,
                 't', coalesce(v.tr_ru->>0, ''), 'ex', v.examples->0->>'s', 'et', nullif(v.examples->0->>'t', ''),
                 'src', 'set:' || p_id, 'st', 0, 'due', ms + i, 'a', ms + i, 'u', ms + i)), now());
      added := added + 1;
    else
      linked := linked + 1;
    end if;
    -- карточка ученика смотрит именно на это слово словаря (у слова может быть несколько частей речи)
    update public.student_vocabulary set word_id = v.id, updated_at = now()
     where site = 'school' and student = s and card_id = card and word_id <> v.id;
  end loop;
  if (select count(*) from public.vocab where student = s) > 5000 then raise exception 'too_many'; end if;
  return jsonb_build_object('added', added, 'linked', linked, 'material', m);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- весь словарь целиком (прежний вызов сайта)
