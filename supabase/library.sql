-- урок с блоками для страницы урока: преподавателю — любой, ученику — если урок есть в его домашке
create or replace function public.lib_lesson_get(p_name text, p_pin text, p_id bigint)
returns jsonb as $fn$
declare n text; r public.library_lessons; k text := 'lib-' || p_id;
begin
  n := public._school_auth(p_name, p_pin);
  select * into r from public.library_lessons where id = p_id;
  if not found then raise exception 'no_lesson'; end if;
  if not exists (select 1 from public.teachers where name = n and status = 'active')
     and not exists (select 1 from public.homework h where h.student = n
       and (h.items @> jsonb_build_array(jsonb_build_object('l', k)) or h.theory @> jsonb_build_array(jsonb_build_object('l', k)))) then
    raise exception 'no_access';
  end if;
  return public._lib_lesson_json(r);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

