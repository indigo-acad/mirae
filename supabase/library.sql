-- блок и его теги: проверка размера и вида
create or replace function public._lib_check(p jsonb)
returns void as $fn$
declare x jsonb;
begin
  if p is null or jsonb_typeof(p) <> 'object' then raise exception 'bad_input'; end if;
  if jsonb_typeof(p->'block') is distinct from 'object' or length((p->'block')::text) > 40000
     or coalesce(p->'block'->>'type', '') !~ '^[a-z_]{1,30}$' then raise exception 'bad_input'; end if;
  if coalesce(p->>'lang', 'ko') !~ '^[a-z]{2}$' or length(coalesce(p->>'level', '')) > 20 or length(coalesce(p->>'topic', '')) > 80
     or length(coalesce(p->>'source', '')) > 120 then raise exception 'bad_input'; end if;
  if p ? 'tags' and p->'tags' <> 'null'::jsonb then
    if jsonb_typeof(p->'tags') <> 'array' or jsonb_array_length(p->'tags') > 20 then raise exception 'bad_input'; end if;
    for x in select * from jsonb_array_elements(p->'tags') loop
      if jsonb_typeof(x) <> 'string' or length(x #>> '{}') not between 1 and 60 then raise exception 'bad_input'; end if;
    end loop;
  end if;
end;
$fn$ language plpgsql immutable security definer set search_path = public, extensions;

create or replace function public._lib_json(b public.library_blocks, t text)
returns jsonb as $fn$
  select jsonb_build_object('id', b.id, 'lang', b.lang, 'kind', b.kind, 'title', b.title, 'level', b.level, 'topic', b.topic,
    'tags', b.tags, 'source', b.source, 'author', b.author, 'block', b.block,
    'fav', exists (select 1 from public.library_favs f where f.teacher = t and f.block_id = b.id),
    'updated', (extract(epoch from b.updated_at) * 1000)::bigint);
$fn$ language sql stable security definer set search_path = public, extensions;

-- урок с блоками: вид window.LESSONS (sections[].blocks), удалённые блоки пропускаются
create or replace function public._lib_lesson_json(r public.library_lessons)
returns jsonb as $fn$
  select jsonb_build_object('id', r.id, 'lang', r.lang, 'title', r.title, 'subtitle', r.subtitle, 'level', r.level,
    'topic', r.topic, 'author', r.author, 'updated', (extract(epoch from r.updated_at) * 1000)::bigint,
    'sections', coalesce((select jsonb_agg(jsonb_build_object('id', s->>'id', 'title', s->>'title', 'icon', coalesce(s->>'icon', ''),
        'part', s->'part', 'b', s->'b',
        'blocks', coalesce((select jsonb_agg(lb.block order by e.ord)
          from jsonb_array_elements_text(s->'b') with ordinality e(v, ord)
          join public.library_blocks lb on lb.id = e.v::bigint), '[]'::jsonb)) order by so)
      from jsonb_array_elements(r.sections) with ordinality x(s, so)), '[]'::jsonb));
$fn$ language sql stable security definer set search_path = public, extensions;

