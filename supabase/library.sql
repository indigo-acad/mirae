-- ---------- 3. Блоки ----------
-- собрать блоки из уроков сайта: [{source, lang, level, topic, tags, block}, …], до 300 за раз.
-- Повторный сбор обновляет сам блок; уровень, тему и теги, которые поменял преподаватель, оставляет.
create or replace function public.teacher_lib_import(p_name text, p_pin text, p_items jsonb)
returns jsonb as $fn$
declare t text; it jsonb; added int := 0; upd int := 0; ins boolean;
begin
  t := public._school_teacher(p_name, p_pin);
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) not between 1 and 300 then raise exception 'bad_input'; end if;
  for it in select * from jsonb_array_elements(p_items) loop
    perform public._lib_check(it);
    if coalesce(it->>'source', '') = '' then raise exception 'bad_input'; end if;
    insert into public.library_blocks(lang, kind, title, block, level, topic, tags, source, author)
    values (coalesce(it->>'lang', 'ko'), it->'block'->>'type', left(coalesce(it->'block'->>'title', ''), 200), it->'block',
            coalesce(it->>'level', ''), coalesce(it->>'topic', ''), coalesce(nullif(it->'tags', 'null'::jsonb), '[]'::jsonb), it->>'source', t)
    on conflict (source) where source is not null do update
      set block = excluded.block, kind = excluded.kind, title = excluded.title, lang = excluded.lang,
          level = case when library_blocks.level = '' then excluded.level else library_blocks.level end,
          topic = case when library_blocks.topic = '' then excluded.topic else library_blocks.topic end,
          tags = case when library_blocks.tags = '[]'::jsonb then excluded.tags else library_blocks.tags end,
          updated_at = now()
      where library_blocks.block is distinct from excluded.block
    returning (xmax = 0) into ins;
    if found then if ins then added := added + 1; else upd := upd + 1; end if; end if;
  end loop;
  return jsonb_build_object('added', added, 'updated', upd);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- поиск. p_f: {lang, kind: [..], level, topic, tag, q, fav, mine, practice, limit, offset}
create or replace function public.teacher_lib_search(p_name text, p_pin text, p_f jsonb)
returns jsonb as $fn$
declare t text; f jsonb := coalesce(p_f, '{}'::jsonb); k text[]; q text; lim int; off int; tot int; res jsonb;
begin
  t := public._school_teacher(p_name, p_pin);
  if jsonb_typeof(f) <> 'object' then raise exception 'bad_input'; end if;
  k := case when jsonb_typeof(f->'kind') = 'array' then array(select jsonb_array_elements_text(f->'kind')) end;
  q := replace(replace(replace(trim(coalesce(f->>'q', '')), '\', '\\'), '%', '\%'), '_', '\_');
  lim := least(greatest(coalesce((f->>'limit')::int, 40), 1), 100);
  off := greatest(coalesce((f->>'offset')::int, 0), 0);
  with m as (
    select b.* from public.library_blocks b
    where (coalesce(f->>'lang', '') = '' or b.lang = f->>'lang')
      and (k is null or cardinality(k) = 0 or b.kind = any(k))
      and (coalesce(f->>'level', '') = '' or b.level = f->>'level')
      and (coalesce(f->>'topic', '') = '' or b.topic = f->>'topic')
      and (coalesce(f->>'tag', '') = '' or b.tags ? (f->>'tag'))
      and (coalesce((f->>'fav')::boolean, false) = false or exists (select 1 from public.library_favs x where x.teacher = t and x.block_id = b.id))
      and (coalesce((f->>'mine')::boolean, false) = false or (b.author = t and b.source is null))
      and (q = '' or b.title ilike '%' || q || '%' or b.topic ilike '%' || q || '%' or b.tags::text ilike '%' || q || '%'
           or b.block::text ilike '%' || q || '%')
  )
  select (select count(*) from m),
         coalesce((select jsonb_agg(public._lib_json(x, t) order by x.lang, x.level, x.topic, x.source nulls last, x.id)
           from (select * from m order by lang, level, topic, source nulls last, id limit lim offset off) x), '[]'::jsonb)
  into tot, res;
  return jsonb_build_object('total', tot, 'items', res);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- что есть в библиотеке: уровни, темы и теги для фильтров
create or replace function public.teacher_lib_facets(p_name text, p_pin text, p_lang text)
returns jsonb as $fn$
declare t text;
begin
  t := public._school_teacher(p_name, p_pin);
  return jsonb_build_object(
    'total', (select count(*) from public.library_blocks where coalesce(p_lang, '') = '' or lang = p_lang),
    'levels', coalesce((select jsonb_agg(l order by l) from (select distinct level l from public.library_blocks where level <> '' and (coalesce(p_lang, '') = '' or lang = p_lang)) x), '[]'::jsonb),
    'topics', coalesce((select jsonb_agg(s order by s) from (select distinct topic s from public.library_blocks where topic <> '' and (coalesce(p_lang, '') = '' or lang = p_lang)) x), '[]'::jsonb),
    'kinds', coalesce((select jsonb_object_agg(kind, n) from (select kind, count(*) n from public.library_blocks where coalesce(p_lang, '') = '' or lang = p_lang group by kind) x), '{}'::jsonb),
    'tags', coalesce((select jsonb_agg(g order by g) from (select distinct jsonb_array_elements_text(tags) g from public.library_blocks where coalesce(p_lang, '') = '' or lang = p_lang) x), '[]'::jsonb));
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- свой блок (без id) или правка блока (с id). Блок правит автор или владелец школы, теги и тему — любой преподаватель.
create or replace function public.teacher_lib_save(p_name text, p_pin text, p_b jsonb)
returns jsonb as $fn$
declare t text; bid bigint; r public.library_blocks;
begin
  t := public._school_teacher(p_name, p_pin);
  perform public._lib_check(p_b);
  bid := nullif(p_b->>'id', '')::bigint;
  if bid is null then
    insert into public.library_blocks(lang, kind, title, block, level, topic, tags, author)
    values (coalesce(p_b->>'lang', 'ko'), p_b->'block'->>'type', left(coalesce(p_b->'block'->>'title', ''), 200), p_b->'block',
            coalesce(p_b->>'level', ''), coalesce(p_b->>'topic', ''), coalesce(nullif(p_b->'tags', 'null'::jsonb), '[]'::jsonb), t)
    returning * into r;
  else
    select * into r from public.library_blocks where id = bid;
    if not found then raise exception 'no_block'; end if;
    if r.block is distinct from (p_b->'block') and r.author is distinct from t and not public._lib_is_owner(t) then raise exception 'not_author'; end if;
    update public.library_blocks set lang = coalesce(p_b->>'lang', lang), kind = p_b->'block'->>'type',
      title = left(coalesce(p_b->'block'->>'title', ''), 200), block = p_b->'block', level = coalesce(p_b->>'level', ''),
      topic = coalesce(p_b->>'topic', ''), tags = coalesce(nullif(p_b->'tags', 'null'::jsonb), '[]'::jsonb), updated_at = now()
    where id = bid returning * into r;
  end if;
  return public._lib_json(r, t);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

create or replace function public.teacher_lib_delete(p_name text, p_pin text, p_id bigint)
returns void as $fn$
declare t text; a text;
begin
  t := public._school_teacher(p_name, p_pin);
  select author into a from public.library_blocks where id = p_id;
  if not found then raise exception 'no_block'; end if;
  if a is distinct from t and not public._lib_is_owner(t) then raise exception 'not_author'; end if;
  delete from public.library_blocks where id = p_id;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

create or replace function public.teacher_lib_fav(p_name text, p_pin text, p_id bigint, p_on boolean)
returns void as $fn$
declare t text;
begin
  t := public._school_teacher(p_name, p_pin);
  if p_on then
    insert into public.library_favs(teacher, block_id) select t, id from public.library_blocks where id = p_id on conflict do nothing;
  else
    delete from public.library_favs where teacher = t and block_id = p_id;
  end if;
end;
