-- MIRAÉ: библиотека упражнений и уроков.
-- Каждое упражнение и каждый блок теории — отдельная запись с тегами: язык, уровень, тема, тип, источник.
-- Блоки из уроков сайта (data/*.js) попадают сюда кнопкой «Собрать из уроков сайта» на странице «Библиотека»
-- (повторный сбор обновляет блоки, теги преподавателя не трогает). Из блоков библиотеки преподаватель собирает
-- свой урок: урок хранит ссылки на блоки, а не копии. Урок из библиотеки открывается как lesson.html?l=lib-<номер>
-- и задаётся домашкой обычным образом: {"l":"lib-<номер>","b":[...]}.
-- Выполнить целиком в Supabase: SQL Editor -> New query -> вставить -> Run. Безопасно запускать повторно.
-- Нужны файлы прошлых шагов: school-access.sql, teachers.sql и homework.sql.

-- ---------- 1. Таблицы ----------
-- block: блок в том же виде, что в data/*.js: {"type":"fill","title":"…","instr":"…","items":[…]}
-- source: откуда блок взят, «урок/раздел-номер» (l12-jiyo/practice-0); у своих блоков преподавателя — null
create table if not exists public.library_blocks (
  id bigint generated by default as identity primary key,
  lang text not null default 'ko' check (lang ~ '^[a-z]{2}$'),
  kind text not null check (kind ~ '^[a-z_]{1,30}$'),
  title text not null default '' check (length(title) <= 200),
  block jsonb not null check (jsonb_typeof(block) = 'object'),
  level text not null default '' check (length(level) <= 20),
  topic text not null default '' check (length(topic) <= 80),
  tags jsonb not null default '[]'::jsonb check (jsonb_typeof(tags) = 'array'),
  source text check (source is null or length(source) <= 120),
  author text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists library_blocks_source_idx on public.library_blocks(source) where source is not null;
create index if not exists library_blocks_lang_idx on public.library_blocks(lang, kind);

-- избранное ♡: у каждого преподавателя своё
create table if not exists public.library_favs (
  teacher text not null,
  block_id bigint not null references public.library_blocks(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (teacher, block_id)
);

-- урок из библиотеки. sections: [{"id":"practice","title":"Отработка","icon":"🔁","part":"practice","b":[12,15,40]}]
create table if not exists public.library_lessons (
  id bigint generated by default as identity primary key,
  lang text not null default 'ko' check (lang ~ '^[a-z]{2}$'),
  title text not null check (length(title) between 1 and 200),
  subtitle text not null default '' check (length(subtitle) <= 300),
  level text not null default '' check (length(level) <= 20),
  topic text not null default '' check (length(topic) <= 80),
  sections jsonb not null check (jsonb_typeof(sections) = 'array'),
  author text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.library_blocks enable row level security;
alter table public.library_favs enable row level security;
alter table public.library_lessons enable row level security;
revoke all on public.library_blocks, public.library_favs, public.library_lessons from anon, authenticated;

