-- ---------- 4. Уроки из библиотеки ----------
create or replace function public.teacher_liblesson_save(p_name text, p_pin text, p_l jsonb)
returns jsonb as $fn$
declare t text; lid bigint; r public.library_lessons; s jsonb; v jsonb; n int := 0; ids text[] := '{}';
begin
  t := public._school_teacher(p_name, p_pin);
  if p_l is null or jsonb_typeof(p_l) <> 'object' or length(trim(coalesce(p_l->>'title', ''))) not between 1 and 200
     or length(coalesce(p_l->>'subtitle', '')) > 300 or coalesce(p_l->>'lang', 'ko') !~ '^[a-z]{2}$'
     or length(coalesce(p_l->>'level', '')) > 20 or length(coalesce(p_l->>'topic', '')) > 80 then raise exception 'bad_input'; end if;
  if jsonb_typeof(p_l->'sections') is distinct from 'array' or jsonb_array_length(p_l->'sections') not between 1 and 12 then raise exception 'bad_input'; end if;
  for s in select * from jsonb_array_elements(p_l->'sections') loop
    if jsonb_typeof(s) <> 'object' or coalesce(s->>'id', '') !~ '^[a-z0-9_]{1,30}$' or coalesce(s->>'id', '') = any(ids)
       or length(coalesce(s->>'title', '')) not between 1 and 80 or length(coalesce(s->>'icon', '')) > 8
       or (s ? 'part' and s->'part' <> 'null'::jsonb and coalesce(s->>'part', '') not in ('theory', 'practice'))
       or jsonb_typeof(s->'b') is distinct from 'array' or jsonb_array_length(s->'b') not between 1 and 40 then raise exception 'bad_input'; end if;
    ids := ids || (s->>'id');
    for v in select * from jsonb_array_elements(s->'b') loop
      if jsonb_typeof(v) <> 'number' or not exists (select 1 from public.library_blocks where id = (v #>> '{}')::bigint) then raise exception 'no_block'; end if;
      n := n + 1;
    end loop;
  end loop;
  if n > 80 then raise exception 'bad_input'; end if;
  lid := nullif(p_l->>'id', '')::bigint;
  if lid is null then
    insert into public.library_lessons(lang, title, subtitle, level, topic, sections, author)
    values (coalesce(p_l->>'lang', 'ko'), trim(p_l->>'title'), trim(coalesce(p_l->>'subtitle', '')), coalesce(p_l->>'level', ''),
            coalesce(p_l->>'topic', ''), p_l->'sections', t)
    returning * into r;
  else
    select * into r from public.library_lessons where id = lid;
    if not found then raise exception 'no_lesson'; end if;
    if r.author is distinct from t and not public._lib_is_owner(t) then raise exception 'not_author'; end if;
    update public.library_lessons set lang = coalesce(p_l->>'lang', 'ko'), title = trim(p_l->>'title'), subtitle = trim(coalesce(p_l->>'subtitle', '')),
      level = coalesce(p_l->>'level', ''), topic = coalesce(p_l->>'topic', ''), sections = p_l->'sections', updated_at = now()
    where id = lid returning * into r;
  end if;
  return public._lib_lesson_json(r);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- список уроков школы, новые сверху (без блоков, только счёт)
create or replace function public.teacher_liblesson_list(p_name text, p_pin text)
returns jsonb as $fn$
declare t text;
begin
  t := public._school_teacher(p_name, p_pin);
  return coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'lang', r.lang, 'title', r.title, 'subtitle', r.subtitle,
      'level', r.level, 'topic', r.topic, 'author', r.author, 'sections', r.sections,
      'n', (select coalesce(sum(jsonb_array_length(s->'b')), 0) from jsonb_array_elements(r.sections) s),
      'updated', (extract(epoch from r.updated_at) * 1000)::bigint) order by r.updated_at desc)
    from (select * from public.library_lessons order by updated_at desc limit 200) r), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

