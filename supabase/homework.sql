-- MIRAÉ: домашка от преподавателя.
-- Преподаватель задаёт ученику домашку: упражнения из уроков (ученик делает их заново, со своими ответами),
-- тренажёры и тесты из каталога, ссылку на теорию, срок и комментарий. Ученик сдаёт домашку на сайте:
-- результаты сохраняются здесь, домашка уходит из кабинета ученика, преподаватель видит баллы и ошибки
-- и может отметить «Проверено» с комментарием.
-- Выполнить целиком в Supabase: SQL Editor -> New query -> вставить -> Run. Безопасно запускать повторно.
-- Нужны файлы прошлых шагов: school-access.sql и teachers.sql.

-- ---------- 1. Таблица ----------
-- items:  [{"l":"l12-jiyo","b":["practice-0","practice-1"]}, {"m":"ko-topik3-vocab"}, {"wt":{...}}]
--         l — урок, b — блоки урока (ключ «раздел-номер», как в прогрессе урока); m — материал из каталога;
--         wt — тест по словам (test.html): {"title":"…","lang":"ko","k":["tr","rev","ctx","wr"],"min":10,
--              "w":[{"w":"слово","t":"перевод","ex":"пример","et":"перевод примера","f":"форма в примере"}, …]}
-- theory: [{"l":"l12-jiyo","s":"grammar"}] — разделы теории, которые ученик может открыть из домашки
-- status: active — задана, done — сдана, checked — проверена преподавателем
create table if not exists public.homework (
  id bigint generated by default as identity primary key,
  student text not null,
  teacher text not null,
  lang text not null default '',
  title text not null,
  items jsonb not null,
  theory jsonb not null default '[]'::jsonb,
  due date,
  note text not null default '',
  status text not null default 'active' check (status in ('active', 'done', 'checked')),
  result jsonb,
  comment text not null default '',
  created_at timestamptz not null default now(),
  submitted_at timestamptz,
  checked_at timestamptz,
  seen_at timestamptz
);
create index if not exists homework_student_idx on public.homework(student, status);
alter table public.homework enable row level security;
revoke all on public.homework from anon, authenticated;

-- ---------- 2. Служебные функции ----------
-- проверка состава домашки: что задано и откуда
create or replace function public._hw_check(p_hw jsonb)
returns void as $fn$
declare it jsonb; b jsonb; n int := 0; k text;
begin
  if p_hw is null or jsonb_typeof(p_hw) <> 'object' or length(p_hw::text) > 20000 then raise exception 'bad_input'; end if;
  if length(trim(coalesce(p_hw->>'title', ''))) not between 1 and 200 then raise exception 'bad_input'; end if;
  if length(coalesce(p_hw->>'note', '')) > 1000 or length(coalesce(p_hw->>'lang', '')) > 5 then raise exception 'bad_input'; end if;
  if jsonb_typeof(p_hw->'items') is distinct from 'array' or jsonb_array_length(p_hw->'items') not between 1 and 40 then raise exception 'bad_input'; end if;
  for it in select * from jsonb_array_elements(p_hw->'items') loop
    if jsonb_typeof(it) <> 'object' then raise exception 'bad_input'; end if;
    if it ? 'm' then
      if not exists (select 1 from public.materials where id = it->>'m') then raise exception 'no_material'; end if;
    elsif it ? 'wt' then
      -- тест по словам: слова лежат в самом задании, ученик проходит его на странице test.html
      if jsonb_typeof(it->'wt') <> 'object' or jsonb_typeof(it->'wt'->'w') is distinct from 'array'
         or jsonb_array_length(it->'wt'->'w') not between 2 and 40 or length(coalesce(it->'wt'->>'title', '')) > 200
         or coalesce(it->'wt'->>'min', '0') !~ '^[0-9]{1,2}$' then raise exception 'bad_input'; end if;
      for b in select * from jsonb_array_elements(it->'wt'->'w') loop
        if jsonb_typeof(b) <> 'object' or length(coalesce(b->>'w', '')) not between 1 and 120 or length(coalesce(b->>'t', '')) not between 1 and 200
           or length(coalesce(b->>'ex', '') || coalesce(b->>'et', '') || coalesce(b->>'f', '')) > 600 then raise exception 'bad_input'; end if;
      end loop;
      if jsonb_typeof(it->'wt'->'k') is distinct from 'array' or jsonb_array_length(it->'wt'->'k') not between 1 and 4 then raise exception 'bad_input'; end if;
      for k in select jsonb_array_elements_text(it->'wt'->'k') loop
        if k not in ('tr', 'rev', 'ctx', 'wr') then raise exception 'bad_input'; end if;
      end loop;
      n := n + 1;
    elsif coalesce(it->>'l', '') ~ '^[a-z0-9-]{1,60}$' and jsonb_typeof(it->'b') = 'array' and jsonb_array_length(it->'b') between 1 and 40 then
      for b in select * from jsonb_array_elements(it->'b') loop
        if jsonb_typeof(b) <> 'string' or (b #>> '{}') !~ '^[a-z0-9_-]{1,60}$' then raise exception 'bad_input'; end if;
        n := n + 1;
      end loop;
    else
      raise exception 'bad_input';
    end if;
  end loop;
  if n > 60 then raise exception 'bad_input'; end if;
  if p_hw ? 'theory' and p_hw->'theory' <> 'null'::jsonb then
    if jsonb_typeof(p_hw->'theory') <> 'array' or jsonb_array_length(p_hw->'theory') > 10 then raise exception 'bad_input'; end if;
    for it in select * from jsonb_array_elements(p_hw->'theory') loop
      if jsonb_typeof(it) <> 'object' or coalesce(it->>'l', '') !~ '^[a-z0-9-]{1,60}$' or coalesce(it->>'s', '') !~ '^[a-z0-9_-]{1,60}$' then
        raise exception 'bad_input';
      end if;
    end loop;
  end if;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- домашка в том виде, в каком её получает сайт: время — в миллисекундах
create or replace function public._hw_json(h public.homework)
returns jsonb as $fn$
  select jsonb_build_object('id', h.id, 'student', h.student, 'teacher', h.teacher, 'lang', h.lang, 'title', h.title,
    'items', h.items, 'theory', h.theory, 'due', h.due, 'note', h.note, 'status', h.status, 'result', h.result,
    'comment', h.comment,
    'created', (extract(epoch from h.created_at) * 1000)::bigint,
    'submitted', (extract(epoch from h.submitted_at) * 1000)::bigint,
    'checked', (extract(epoch from h.checked_at) * 1000)::bigint,
    'seen', (extract(epoch from h.seen_at) * 1000)::bigint);
$fn$ language sql stable security definer set search_path = public, extensions;

revoke execute on function public._hw_check(jsonb) from public, anon, authenticated;
revoke execute on function public._hw_json(public.homework) from public, anon, authenticated;

-- ---------- 3. Преподаватель ----------
-- задать домашку (без id) или поправить ещё не сданную (с id)
create or replace function public.teacher_hw_save(p_name text, p_pin text, p_student text, p_hw jsonb)
returns jsonb as $fn$
declare t text; s text; hid bigint; r public.homework;
begin
  t := public._school_teacher(p_name, p_pin);
  s := public._school_mine(t, p_student);
  if not exists (select 1 from public.progress where site = 'school' and name = s) then raise exception 'no_student'; end if;
  perform public._hw_check(p_hw);
  hid := nullif(p_hw->>'id', '')::bigint;
  if hid is null then
    insert into public.homework(student, teacher, lang, title, items, theory, due, note)
    values (s, t, coalesce(p_hw->>'lang', ''), trim(p_hw->>'title'), p_hw->'items',
            coalesce(nullif(p_hw->'theory', 'null'::jsonb), '[]'::jsonb), nullif(p_hw->>'due', '')::date, trim(coalesce(p_hw->>'note', '')))
    returning * into r;
  else
    update public.homework set lang = coalesce(p_hw->>'lang', ''), title = trim(p_hw->>'title'), items = p_hw->'items',
      theory = coalesce(nullif(p_hw->'theory', 'null'::jsonb), '[]'::jsonb), due = nullif(p_hw->>'due', '')::date,
      note = trim(coalesce(p_hw->>'note', ''))
    where id = hid and student = s and status = 'active'
    returning * into r;
    if not found then raise exception 'no_homework'; end if;
  end if;
  return public._hw_json(r);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- вся домашка ученика: заданная, сданная и проверенная, новые сверху
create or replace function public.teacher_hw_list(p_name text, p_pin text, p_student text)
returns jsonb as $fn$
declare s text;
begin
  s := public._school_mine(public._school_teacher(p_name, p_pin), p_student);
  return coalesce((select jsonb_agg(public._hw_json(h) order by h.created_at desc)
    from (select * from public.homework where student = s order by created_at desc limit 100) h), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

create or replace function public.teacher_hw_delete(p_name text, p_pin text, p_id bigint)
returns void as $fn$
declare t text; s text;
begin
  t := public._school_teacher(p_name, p_pin);
  select student into s from public.homework where id = p_id;
  if not found then raise exception 'no_homework'; end if;
  perform public._school_mine(t, s);
  delete from public.homework where id = p_id;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- отметить сданную домашку проверенной; комментарий ученик увидит в кабинете
create or replace function public.teacher_hw_check(p_name text, p_pin text, p_id bigint, p_comment text)
returns jsonb as $fn$
declare t text; s text; r public.homework;
begin
  t := public._school_teacher(p_name, p_pin);
  select student into s from public.homework where id = p_id;
  if not found then raise exception 'no_homework'; end if;
  perform public._school_mine(t, s);
  if length(coalesce(p_comment, '')) > 2000 then raise exception 'bad_input'; end if;
  update public.homework set status = 'checked', comment = trim(coalesce(p_comment, '')), checked_at = now(),
    seen_at = case when trim(coalesce(p_comment, '')) = '' then now() else null end
  where id = p_id and status in ('done', 'checked')
  returning * into r;
  if not found then raise exception 'not_submitted'; end if;
  return public._hw_json(r);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- ---------- 4. Ученик ----------
-- заданная домашка и сданная за последние 30 дней (чтобы показать комментарий преподавателя)
create or replace function public.my_homework(p_name text, p_pin text)
returns jsonb as $fn$
declare n text;
begin
  n := public._school_auth(p_name, p_pin);
  return coalesce((select jsonb_agg(public._hw_json(h) order by h.created_at)
    from public.homework h
    where h.student = n and (h.status = 'active' or coalesce(h.checked_at, h.submitted_at) > now() - interval '30 days')), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- сдать домашку: результаты по каждому заданию; после этого домашку не поменять
create or replace function public.hw_submit(p_name text, p_pin text, p_id bigint, p_result jsonb)
returns jsonb as $fn$
declare n text; r public.homework;
begin
  n := public._school_auth(p_name, p_pin);
  if p_result is null or jsonb_typeof(p_result) <> 'object' or length(p_result::text) > 60000 then raise exception 'bad_input'; end if;
  update public.homework set status = 'done', result = p_result, submitted_at = now()
  where id = p_id and student = n and status = 'active'
  returning * into r;
  if not found then raise exception 'no_homework'; end if;
  return public._hw_json(r);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- ученик прочитал комментарий преподавателя
create or replace function public.hw_seen(p_name text, p_pin text, p_id bigint)
returns void as $fn$
declare n text;
begin
  n := public._school_auth(p_name, p_pin);
  update public.homework set seen_at = now() where id = p_id and student = n and status = 'checked';
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- ---------- 5. Ученика удалили — его домашка удаляется вместе с ним ----------
create or replace function public._school_hw_cleanup()
returns trigger as $fn$
begin
  if old.site = 'school' then delete from public.homework where student = old.name; end if;
  return old;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;
drop trigger if exists school_hw_cleanup on public.progress;
create trigger school_hw_cleanup after delete on public.progress
  for each row execute function public._school_hw_cleanup();

