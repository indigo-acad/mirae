-- MIRAÉ: группы учеников.
-- Группа — это список учеников одного преподавателя. Всё, что преподаватель делает с группой, раскладывается
-- на каждого ученика уже готовыми функциями (teacher_assign, teacher_set_assign, teacher_vocab_add, teacher_hw_save),
-- поэтому у ученика всё лежит там же, где и при занятиях один на один. Здесь хранится только сама группа:
-- состав, программа группы (какие уроки и словари ей назначены) и занятия с отметкой присутствия.
-- Выполнить целиком в Supabase: SQL Editor -> New query -> вставить -> Run. Безопасно запускать повторно.
-- Нужны прошлые шаги: school-access.sql, teachers.sql (и homework.sql, vocab.sql, vocab2.sql для назначений).

-- ---------- 1. Таблицы ----------
-- plan: {"items":[{"m":"lesson-l12-jiyo","open":true}, …], "sets":[{"s":12,"w":[3,5]|null}, …], "step":true}
--   items — программа группы по порядку: материал каталога; open — уже открыт ученикам группы;
--   sets  — словари, назначенные группе (w — отмеченные слова или null — весь словарь);
--   step  — открывать уроки программы по мере занятий: «Пройден на занятии» открывает следующий.
create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  teacher text not null references public.teachers(name) on update cascade on delete cascade,
  name text not null,
  lang text not null default '',
  plan jsonb not null default '{"items":[],"sets":[],"step":true}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists groups_teacher_idx on public.groups(teacher);

create table if not exists public.group_members (
  group_id bigint not null references public.groups(id) on delete cascade,
  site text not null default 'school' check (site = 'school'),
  student text not null,
  joined_at timestamptz not null default now(),
  primary key (group_id, student),
  foreign key (site, student) references public.progress(site, name) on delete cascade
);
create index if not exists group_members_student_idx on public.group_members(student);

-- занятие группы: день, урок (id материала, например lesson-l12-jiyo, или пусто), кто был, кто опоздал, кого не было
create table if not exists public.group_sessions (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  day date not null default current_date,
  lesson text not null default '',
  title text not null default '',
  present text[] not null default '{}',
  late text[] not null default '{}',
  absent text[] not null default '{}',
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists group_sessions_group_idx on public.group_sessions(group_id, day desc);

alter table public.groups enable row level security;
alter table public.group_members enable row level security;
alter table public.group_sessions enable row level security;
revoke all on public.groups, public.group_members, public.group_sessions from anon, authenticated;

-- ---------- 2. Служебные функции ----------
-- группа доступна преподавателю: владельцу школы — любая, остальным — только своя
create or replace function public._grp_mine(p_teacher text, p_group bigint)
returns bigint as $fn$
begin
  if not exists (select 1 from public.groups g where g.id = p_group
                  and (g.teacher = p_teacher or exists (select 1 from public.teachers t where t.name = p_teacher and t.role = 'owner'))) then
    raise exception 'no_group';
  end if;
  return p_group;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

create or replace function public._grp_json(g public.groups)
returns jsonb as $fn$
  select jsonb_build_object('id', g.id, 'name', g.name, 'lang', g.lang, 'teacher', g.teacher, 'plan', g.plan, 'created_at', g.created_at,
    'members', coalesce((select jsonb_agg(jsonb_build_object('name', m.student, 'joined_at', m.joined_at) order by m.student)
                           from public.group_members m where m.group_id = g.id), '[]'::jsonb),
    'sessions', (select count(*) from public.group_sessions s where s.group_id = g.id),
    'last', (select max(s.day) from public.group_sessions s where s.group_id = g.id));
$fn$ language sql security definer set search_path = public, extensions;

create or replace function public._grp_session_json(s public.group_sessions)
returns jsonb as $fn$
  select jsonb_build_object('id', s.id, 'group', s.group_id, 'day', s.day, 'lesson', s.lesson, 'title', s.title,
    'present', to_jsonb(s.present), 'late', to_jsonb(s.late), 'absent', to_jsonb(s.absent), 'note', s.note, 'created_at', s.created_at);
$fn$ language sql security definer set search_path = public, extensions;

-- список логинов из jsonb-массива: без повторов, только ученики этого преподавателя
create or replace function public._grp_students(p_teacher text, p_list jsonb)
returns text[] as $fn$
declare r text[] := '{}'; x jsonb; s text;
begin
  if p_list is null or p_list = 'null'::jsonb then return r; end if;
  if jsonb_typeof(p_list) <> 'array' or jsonb_array_length(p_list) > 60 then raise exception 'bad_input'; end if;
  for x in select * from jsonb_array_elements(p_list) loop
    if jsonb_typeof(x) <> 'string' then raise exception 'bad_input'; end if;
    s := public._school_mine(p_teacher, x #>> '{}');
    if exists (select 1 from public.teachers where name = s)
       or not exists (select 1 from public.progress where site = 'school' and name = s) then raise exception 'no_student'; end if;
    if not (s = any(r)) then r := r || s; end if;
  end loop;
  return r;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

revoke execute on function public._grp_mine(text, bigint) from public, anon, authenticated;
revoke execute on function public._grp_json(public.groups) from public, anon, authenticated;
revoke execute on function public._grp_session_json(public.group_sessions) from public, anon, authenticated;
revoke execute on function public._grp_students(text, jsonb) from public, anon, authenticated;

-- ---------- 3. Группы ----------
-- группы преподавателя (владелец видит все)
create or replace function public.teacher_groups(p_name text, p_pin text)
returns jsonb as $fn$
declare t text; own boolean;
begin
  t := public._school_teacher(p_name, p_pin);
  own := exists (select 1 from public.teachers where name = t and role = 'owner');
  return coalesce((select jsonb_agg(public._grp_json(g) order by g.name) from public.groups g where own or g.teacher = t), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- создать или изменить группу: {"id"?, "name", "lang", "plan"?, "members"?: ["логин", …]}
-- Если members передан, состав становится ровно таким; новые ученики возвращаются в поле added, ушедшие — в removed.
create or replace function public.teacher_group_save(p_name text, p_pin text, p_group jsonb)
returns jsonb as $fn$
declare t text; gid bigint; g public.groups; mem text[]; old text[]; added text[] := '{}'; removed text[] := '{}'; s text;
begin
  t := public._school_teacher(p_name, p_pin);
  if p_group is null or jsonb_typeof(p_group) <> 'object' or length(p_group::text) > 30000 then raise exception 'bad_input'; end if;
  if length(trim(coalesce(p_group->>'name', ''))) not between 1 and 80 then raise exception 'bad_input'; end if;
  if coalesce(p_group->>'lang', '') not in ('', 'ko', 'en') then raise exception 'bad_input'; end if;
  if p_group ? 'plan' and jsonb_typeof(p_group->'plan') <> 'object' then raise exception 'bad_input'; end if;
  gid := nullif(p_group->>'id', '')::bigint;
  if gid is null then
    insert into public.groups(teacher, name, lang, plan)
    values (t, trim(p_group->>'name'), coalesce(p_group->>'lang', ''),
            coalesce(p_group->'plan', '{"items":[],"sets":[],"step":true}'::jsonb))
    returning * into g;
  else
    perform public._grp_mine(t, gid);
    update public.groups set name = trim(p_group->>'name'), lang = coalesce(p_group->>'lang', ''),
      plan = coalesce(p_group->'plan', plan)
     where id = gid returning * into g;
  end if;
  if p_group ? 'members' then
    mem := public._grp_students(t, p_group->'members');
    select coalesce(array_agg(student), '{}') into old from public.group_members where group_id = g.id;
    foreach s in array mem loop if not (s = any(old)) then added := added || s; end if; end loop;
    foreach s in array old loop if not (s = any(mem)) then removed := removed || s; end if; end loop;
    delete from public.group_members where group_id = g.id and not (student = any(mem));
    insert into public.group_members(group_id, student) select g.id, x from unnest(added) x on conflict do nothing;
  end if;
  return public._grp_json(g) || jsonb_build_object('added', to_jsonb(added), 'removed', to_jsonb(removed));
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- удалить группу: ученики, их назначения, слова и домашка остаются, пропадают только группа и журнал занятий
create or replace function public.teacher_group_delete(p_name text, p_pin text, p_id bigint)
returns void as $fn$
begin
  perform public._grp_mine(public._school_teacher(p_name, p_pin), p_id);
  delete from public.groups where id = p_id;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- ---------- 4. Занятия и посещаемость ----------
create or replace function public.teacher_group_sessions(p_name text, p_pin text, p_id bigint)
returns jsonb as $fn$
begin
  perform public._grp_mine(public._school_teacher(p_name, p_pin), p_id);
  return coalesce((select jsonb_agg(public._grp_session_json(s) order by s.day desc, s.id desc)
                     from public.group_sessions s where s.group_id = p_id), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- записать занятие: {"id"?, "day", "lesson", "title", "present":[…], "late":[…], "absent":[…], "note"}
-- Ученик стоит только в одном списке: «опоздал» важнее «был», «не был» — если его нет в первых двух.
create or replace function public.teacher_group_session_save(p_name text, p_pin text, p_group bigint, p_s jsonb)
returns jsonb as $fn$
declare t text; sid bigint; r public.group_sessions; pr text[]; la text[]; ab text[];
begin
  t := public._school_teacher(p_name, p_pin);
  perform public._grp_mine(t, p_group);
  if p_s is null or jsonb_typeof(p_s) <> 'object' or length(p_s::text) > 8000 then raise exception 'bad_input'; end if;
  if length(coalesce(p_s->>'lesson', '')) > 80 or length(coalesce(p_s->>'title', '')) > 200 or length(coalesce(p_s->>'note', '')) > 1000 then raise exception 'bad_input'; end if;
  la := public._grp_students(t, p_s->'late');
  pr := array(select x from unnest(public._grp_students(t, p_s->'present')) x where not (x = any(la)));
  ab := array(select x from unnest(public._grp_students(t, p_s->'absent')) x where not (x = any(la)) and not (x = any(pr)));
  sid := nullif(p_s->>'id', '')::bigint;
  if sid is null then
    insert into public.group_sessions(group_id, day, lesson, title, present, late, absent, note)
    values (p_group, coalesce(nullif(p_s->>'day', '')::date, current_date), coalesce(p_s->>'lesson', ''), trim(coalesce(p_s->>'title', '')),
            pr, la, ab, trim(coalesce(p_s->>'note', '')))
    returning * into r;
  else
    update public.group_sessions set day = coalesce(nullif(p_s->>'day', '')::date, day), lesson = coalesce(p_s->>'lesson', ''),
      title = trim(coalesce(p_s->>'title', '')), present = pr, late = la, absent = ab, note = trim(coalesce(p_s->>'note', ''))
     where id = sid and group_id = p_group returning * into r;
    if not found then raise exception 'no_session'; end if;
  end if;
  return public._grp_session_json(r);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

create or replace function public.teacher_group_session_delete(p_name text, p_pin text, p_id bigint)
returns void as $fn$
declare gid bigint;
begin
  select group_id into gid from public.group_sessions where id = p_id;
  if gid is null then raise exception 'no_session'; end if;
  perform public._grp_mine(public._school_teacher(p_name, p_pin), gid);
  delete from public.group_sessions where id = p_id;
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- посещаемость ученика по его группам — для карточки ученика в панели
create or replace function public.teacher_student_groups(p_name text, p_pin text, p_student text)
returns jsonb as $fn$
declare s text;
begin
  s := public._school_mine(public._school_teacher(p_name, p_pin), p_student);
  return coalesce((select jsonb_agg(jsonb_build_object('id', g.id, 'name', g.name,
      'total', (select count(*) from public.group_sessions x where x.group_id = g.id and (s = any(x.present) or s = any(x.late) or s = any(x.absent))),
      'present', (select count(*) from public.group_sessions x where x.group_id = g.id and s = any(x.present)),
      'late', (select count(*) from public.group_sessions x where x.group_id = g.id and s = any(x.late)),
      'missed', coalesce((select jsonb_agg(jsonb_build_object('day', x.day, 'lesson', x.lesson, 'title', x.title) order by x.day desc)
                            from public.group_sessions x where x.group_id = g.id and s = any(x.absent)), '[]'::jsonb)) order by g.name)
    from public.groups g join public.group_members m on m.group_id = g.id and m.student = s), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

-- ученик: занятия его групп — какие уроки прошли на занятии с ним, какие он пропустил
create or replace function public.my_group_sessions(p_name text, p_pin text)
returns jsonb as $fn$
declare s text;
begin
  s := public._school_auth(p_name, p_pin);
  return coalesce((select jsonb_agg(jsonb_build_object('day', x.day, 'lesson', x.lesson, 'title', x.title, 'group', g.name,
             'st', case when s = any(x.present) then 'present' when s = any(x.late) then 'late' else 'absent' end) order by x.day desc)
      from public.group_sessions x join public.groups g on g.id = x.group_id
     where s = any(x.present) or s = any(x.late) or s = any(x.absent)), '[]'::jsonb);
end;
$fn$ language plpgsql security definer set search_path = public, extensions;

